import Link from "next/link";
import { requirePageRole } from "@/lib/auth/session";

export const dynamic = "force-dynamic";

// Organizer manual: how brackets are built and what each control in the console does.
export default async function OrganizerHelp({ params }: { params: Promise<{ eventId: string }> }) {
  const { eventId } = await params;
  await requirePageRole("ORGANIZER", "ADMIN", "MAT_COORDINATOR");
  const base = `/organizer/${eventId}`;

  return (
    <main className="mx-auto max-w-3xl p-6 leading-relaxed">
      <Link href={base} className="text-sm text-blue-600">← Пульт организатора</Link>
      <h1 className="mt-2 text-2xl font-bold">Как работать с пультом</h1>
      <p className="mt-2 text-gray-600">
        Здесь по порядку описан день турнира: от заявок до призёров. Если нужно только одно место — пролистайте до
        нужного раздела, они не зависят друг от друга.
      </p>

      <Section title="Как устроен пульт">
        <p>
          Пульт организатора — одна длинная страница. Сверху ссылки и кнопки на весь турнир, ниже таблица заявок,
          под ней предложения объединить мелкие категории, блок абсолютки и, наконец, список всех категорий со
          взвешиванием. У каждой категории есть собственная страница «Состав и сетка» — там делается всё, что
          касается одной категории.
        </p>
      </Section>

      <Section title="Кнопки вверху">
        <Item name="Сетки без интернета →">
          Пульт для ввода результатов, который продолжает работать, когда пропадает сеть. Откройте его один раз на
          каждом устройстве, пока интернет есть: сетки сохранятся в браузере. Без сети результаты копятся на
          устройстве, сетка двигается сразу, а на сайт всё уходит само, как только связь вернётся. Если на сайте ту
          же схватку уже записали с другим победителем, пульт покажет расхождение и даст выбрать, чей вариант оставить.
        </Item>
        <Item name="Список в Excel">
          Все участники турнира: по строке на каждую категорию, с клубом, телефоном, весом, статусом и оплатой.
          Сверху фильтр, чтобы быстро отобрать клуб или возраст.
        </Item>
        <Item name="Сетки в Excel">
          Все собранные сетки, по листу на категорию, плюс лист «Призёры». Победителя выбирают из списка в жёлтой
          колонке — следующие пары, схватка за 3-е место и призёры заполняются формулами. Это запасной вариант на
          случай, если откажет всё; обратно на сайт файл не загружается.
        </Item>
        <Item name="Командный зачёт →">Таблица клубов по медалям, считается сама по результатам.</Item>
        <Item name="Закрыть взвешивание · старт">
          Переводит турнир в режим «идёт». После этого взвешивать и допускать через пульт нельзя, поэтому нажимайте,
          когда взвешивание всех возрастов действительно закончено.
        </Item>
      </Section>

      <Section title="Заявки участников">
        <p>
          Таблица всех заявок, неоплаченные подсвечены жёлтым и стоят сверху. Поиск по ФИО над таблицей. Пометка
          «дубль?» означает, что совпали фамилия и имя — скорее всего, человек заявился сам и его же заявил тренер;
          лишнюю заявку удалите.
        </p>
        <Item name="изменить">Исправить ФИО, дату рождения, клуб, телефон участника.</Item>
        <Item name="удалить">Удалить заявку целиком. Запись об удалении сохраняется, при ошибке её можно восстановить через администратора.</Item>
        <Item name="Категории (перенос)">
          Текущая категория участника. «сменить» открывает список — выберите другую, и регистрация переедет туда
          сама. Если в старой категории уже была сетка, её нужно пересобрать.
        </Item>
        <Item name="Оплата">
          Отметка для организаторов: «оплатил», «оплатит позже», «бесплатно» или «не оплачено». Публично любая
          отметка, кроме последней, видна как «оплачено».
        </Item>
      </Section>

      <Section title="Как сайт собирает сетку">
        <p>
          В сетку попадают все, кто заявлен в категорию, — взвешиваться для этого не обязательно. Не попадают только
          те, кого убрали вручную, и те, кого на взвешивании признали перевесом без подходящей категории.
        </p>
        <p>
          Сетка — олимпийская система. Если участников не степень двойки, лишние места заполняются проходами: кто-то
          сразу выходит во второй круг. Одноклубники и однофамильцы по возможности разводятся по разным половинам.
          Победитель каждой схватки сам переходит в следующую, проигравшие полуфиналов — в схватку за 3-е место.
        </p>
        <ul className="list-disc space-y-1 pl-6">
          <li><b>1 участник</b> — схваток нет, он побеждает без боя.</li>
          <li><b>2 участника</b> — одна схватка, финал.</li>
          <li><b>3 участника</b> — один сразу в финале, двое в полуфинале; проигравший полуфинал занимает 3-е место без боя.</li>
          <li><b>4 и больше</b> — полная сетка со схваткой за 3-е место.</li>
        </ul>
        <p>
          У каждой категории есть ковёр (выпадающий список «ковёр» в её строке). Его можно выбрать до сборки сетки
          или после — номер проставится во все схватки категории и сохранится при пересборке.
        </p>
      </Section>

      <Section title="Категории и взвешивание">
        <p>
          В строке каждой категории: сколько участников допущено и сколько заявлено, ковёр, кнопка «Состав и сетка» и
          кнопка «Сгенерировать сетку» (или «Пересобрать сетку», если она уже есть). Ниже — невзвешенные участники
          с полем веса.
        </p>
        <Item name="допустить (взвешивание)">
          Введите фактический вес и нажмите «допустить». Если вес в пределах категории — участник допущен. Если
          больше — сайт переводит его в ближайшую подходящую категорию сверху и допускает там; если такой нет, ставит
          «перевес», и в сетку участник не попадает. После перевода обе сетки — старую и новую — нужно пересобрать.
          Вернуть участника в его категорию можно на странице «Состав и сетка».
        </Item>
        <Item name="+ Создать категорию вручную">
          Новая категория по образцу существующей: возраст, пол, дисциплина, уровень и ковёр берутся из образца, вес
          и название группы задаёте сами. После создания сразу открывается её «Состав и сетка», где набираются участники.
        </Item>
        <Item name="Предложения по объединению">
          Сайт подсказывает, какие маленькие категории можно слить с соседней по весу. «объединить» переносит всех
          участников в соседнюю категорию.
        </Item>
        <Item name="Абсолютка">
          Отдельный блок: добавить участников турнира в абсолютную категорию и сверстать её сетку.
        </Item>
      </Section>

      <Section title="Страница «Состав и сетка»">
        <p>Всё про одну категорию. Ничего на этой странице не затрагивает другие категории.</p>
        <Item name="Разобрать сетку">
          Удаляет схватки только этой категории. Участники остаются в списке, их можно добавить, убрать и снова
          собрать сетку.
        </Item>
        <Item name="Сохранить сетку">
          Собирает сетку из текущего списка. Если перед этим участников меняли местами, перестановка собьётся — её
          придётся повторить.
        </Item>
        <Item name="убрать / вернуть">
          Убирает участника из этой категории, но не удаляет: внизу появится строка «Убраны» с кнопкой «вернуть».
        </Item>
        <Item name="Добавить участника">
          Поиск по фамилии среди всех заявленных на турнир. «добавить» ставит найденного в эту категорию. Если он
          стоит ещё в какой-то категории, там он тоже остаётся — уберите его там на её странице. Ссылка «Человека нет
          на сайте» открывает форму: ФИО, дата рождения, клуб (можно пусто) и вес — человек сразу заявляется на
          турнир. Каждая добавленная категория прибавляет к взносу цену дополнительной категории; отметку об
          оплате ставьте сами.
        </Item>
        <Item name="Расстановка в сетке">
          Поменять двоих участников местами, поставить участника на нужный номер посева и одним нажатием развести
          одноклубников, если они встретились в первом круге.
        </Item>
        <Item name="Скачать Excel">Таблица одной категории: список участников и, если есть, её сетка с формулами.</Item>
        <p className="text-gray-600">
          Как только в категории записан хотя бы один результат, состав и сетку на этой странице менять нельзя —
          чтобы не потерять уже сыгранное.
        </p>
      </Section>

      <Section title="Результаты схваток">
        <p>
          Результаты вводят на публичной странице категории через кнопку «Судейский пульт» или в пульте «Сетки без
          интернета». Выбираете победителя и способ победы — сетка двигается сама: победитель появляется в следующей
          паре, проигравшие полуфиналов — в схватке за 3-е место, призёры — в шапке категории. Публичная страница
          сетки показывает изменения после обновления.
        </p>
      </Section>
    </main>
  );
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section className="mt-8 space-y-3">
      <h2 className="text-xl font-semibold">{title}</h2>
      {children}
    </section>
  );
}

function Item({ name, children }: { name: string; children: React.ReactNode }) {
  return (
    <div>
      <div className="font-semibold">«{name}»</div>
      <div className="text-gray-700">{children}</div>
    </div>
  );
}
